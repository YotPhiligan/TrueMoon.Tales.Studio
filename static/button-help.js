export const buttonSelector='button,[role="button"],input:is([type="button"],[type="submit"],[type="reset"]),.story-tracks > summary,a.button[download]';

export function buttonHelp(button){
  const title=button.getAttribute('title')?.trim();
  const label=(button.getAttribute('aria-label')??button.textContent).trim().replace(/\s+/g,' ');
  if(button.dataset.tooltip)return button.dataset.tooltip;
  const help=Object.hasOwn(byId,button.id)?byId[button.id]:
    commands[button.dataset.command]||
    (button.closest('[data-asset-actions]')?(assetActions[label]??'Применяет это действие к выбранному файлу.'):null)||
    rules.find(([selector])=>button.matches(selector))?.[1]||
    (button.type==='submit'?submitHelp[button.form?.id]:null);
  if(help){
    const context=button.matches('[data-kind]:not([data-sound-event]), [data-title-edit], [data-nav-toggle]');
    return context&&title?title+'\n'+help:help;
  }
  return title||label||button.value||'Выполняет действие текущей формы.';
}
